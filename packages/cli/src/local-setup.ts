const WEB_KEYS = ['TURNSTILE_SITE_KEY']

function serializeEnv(values: Record<string, string>): string {
  return `${Object.entries(values)
    .map(([key, value]) => {
      if (/[\r\n]/.test(value)) throw new Error(`Multiline value is unsupported for ${key}`)
      // Node/Wrangler dotenv preserve backslashes literally in quoted values.
      const quote = value.includes('"') ? "'" : '"'
      if (value.includes(quote)) throw new Error(`Unsupported quote combination for ${key}`)
      return `${key}=${quote}${value}${quote}`
    })
    .join('\n')}\n`
}

export interface LocalPlan {
  files: FileToWrite[]
  conflicts: string[]
}

export function planLocalEnvironment(root: string): LocalPlan {
  const config = readSaasConfig(root)
  const env = readLocalEnv(join(root, ENV_LOCAL_FILENAME))
  if (!env.BETTER_AUTH_SECRET || env.BETTER_AUTH_SECRET.length < 32) {
    throw new Error(
      'Set BETTER_AUTH_SECRET (at least 32 characters) in .env.local; run pnpm wizard for a new installation.',
    )
  }
  const s3Keys = ['R2_ACCESS_KEY_ID', 'R2_SECRET_ACCESS_KEY', 'CLOUDFLARE_ACCOUNT_ID']
  if (s3Keys.some((key) => env[key])) {
    if (!s3Keys.every((key) => env[key]))
      throw new Error('R2 signing requires all three S3 credential/account keys')
    const worker = readJsonc(join(root, 'apps/api/wrangler.jsonc'))
    const buckets = worker.r2_buckets as Array<{ binding: string; bucket_name: string }> | undefined
    if (
      !env.R2_BUCKET_NAME ||
      env.R2_BUCKET_NAME !== buckets?.find((bucket) => bucket.binding === 'BUCKET')?.bucket_name
    ) {
      throw new Error(
        'R2_BUCKET_NAME must match the local API BUCKET binding before enabling S3 signing',
      )
    }
  }
  const publicValues = { APP_URL: config.appUrl, BILLING_PROVIDER: config.billing.provider }
  const billingEnvironment =
    config.billing.provider === 'none' ? 'sandbox' : config.billing.environment
  for (const [key, value] of Object.entries({
    ...publicValues,
    POLAR_ENVIRONMENT: billingEnvironment,
  })) {
    if (env[key] !== undefined && env[key] !== value)
      throw new Error(
        `Configuration conflict: ${key} differs between saas.config.ts and .env.local; reconcile manually.`,
      )
  }
  const defaults: Record<string, Record<string, string>> = {
    api: { ...publicValues, ENVIRONMENT: 'development', POLAR_ENVIRONMENT: billingEnvironment },
    jobs: {
      APP_URL: config.appUrl,
      APP_NAME: config.projectName,
      EMAIL_FROM: 'dev@localhost',
      AUDIT_LOG_RETENTION_DAYS: '90',
      ORPHAN_OBJECT_GRACE_DAYS: '7',
      STALE_OUTBOX_HOURS: '24',
    },
    web: { APP_URL: config.appUrl },
  }
  const conflicts: string[] = []
  const files: FileToWrite[] = []
  for (const [app, keys] of Object.entries({ api: API_KEYS, jobs: JOBS_KEYS, web: WEB_KEYS })) {
    const desired = { ...defaults[app] }
    for (const key of keys) if (env[key] !== undefined) desired[key] = env[key]
    const path = `apps/${app}/.dev.vars`
    const existingPath = join(root, path)
    const existing = readLocalEnv(existingPath)
    if (existsSync(existingPath)) {
      const changed = Object.keys(desired).filter((key) => existing[key] !== desired[key])
      if (changed.length) conflicts.push(`${path}: ${changed.join(', ')}`)
      else continue
    }
    // Retain custom worker-only keys when explicitly reconciling managed values.
    files.push({
      path,
      content: `# Local worker configuration; generated by pnpm bootstrap. Never commit.\n${serializeEnv({ ...existing, ...desired })}`,
      ownerOnlyPerms: true,
    })
  }
  return { files, conflicts }
}

export interface BootstrapOptions {
  dryRun?: boolean
  preflight?: boolean
  force?: boolean
  run?: (command: string, args: string[]) => void
  log?: (message: string) => void
}

export async function bootstrapLocal(
  root: string,
  options: BootstrapOptions = {},
): Promise<LocalPlan> {
  const plan = planLocalEnvironment(root)
  const log = options.log ?? console.log
  for (const file of plan.files) log(`Planned local configuration: ${file.path}`)
  if (plan.conflicts.length && !options.force) {
    throw new Error(
      `Existing worker configuration differs: ${plan.conflicts.join('; ')}. No files changed. Reconcile manually or explicitly use --force to update managed keys.`,
    )
  }
  log('Local commands: pnpm db:migrate; pnpm db:seed (no remote operations).')
  if (options.dryRun || options.preflight) return plan
  await writeFiles(root, plan.files, async () => options.force === true)
  const run =
    options.run ??
    ((command, args) => {
      execFileSync(command, args, {
        cwd: root,
        stdio: 'inherit',
        shell: process.platform === 'win32',
      })
    })
  run('pnpm', ['db:migrate'])
  run('pnpm', ['db:seed'])
  return plan
}

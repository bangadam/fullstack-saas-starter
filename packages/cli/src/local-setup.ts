import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { parseEnv } from 'node:util'
import {
  CONFIG_FILENAME,
  ENV_LOCAL_FILENAME,
  type SaasConfig,
  saasConfigSchema,
} from './config-schema.js'
import { readJsonc } from './deploy.js'
import { type FileToWrite, writeFiles } from './write-files.js'

export function configToTs(config: SaasConfig): string {
  return `import type { SaasConfig } from '@saas/cli'\n\nexport default ${JSON.stringify(config, null, 2)} satisfies SaasConfig\n`
}

/** Read data, never import or execute a user's configuration module. */
export function readSaasConfig(root: string): SaasConfig {
  const path = join(root, CONFIG_FILENAME)
  if (!existsSync(path)) throw new Error('Missing saas.config.ts; run pnpm wizard --yes first.')
  try {
    const source = readFileSync(path, 'utf8')
    const body = /export default\s+(\{[\s\S]*\})\s+satisfies SaasConfig\s*;?\s*$/.exec(source)?.[1]
    if (!body) throw new Error('Unsupported configuration shape')
    // Accept the original wizard's unquoted keys and single-quoted literals too.
    const json = body
      .replace(/'([^'\\]*)'/g, (_, value: string) => JSON.stringify(value))
      .replace(
        /([{,]\s*)(schemaVersion|projectName|preset|billing|appUrl|provider|environment)\s*:/g,
        '$1"$2":',
      )
      .replace(/,\s*}/g, '}')
    return saasConfigSchema.parse(JSON.parse(json))
  } catch {
    throw new Error(
      'Invalid saas.config.ts; use the static object format generated by pnpm wizard.',
    )
  }
}

export function readLocalEnv(path: string): Record<string, string> {
  const values = existsSync(path) ? parseEnv(readFileSync(path, 'utf8')) : {}
  return Object.fromEntries(
    Object.entries(values).filter(
      (entry): entry is [string, string] => typeof entry[1] === 'string',
    ),
  )
}

